import { TestBed } from '@angular/core/testing';
import { CanActivateFn } from '@angular/router';
import { authGuard } from './auth-guard';

describe('authGuard', () => {
  const executeGuard: CanActivateFn = (...guardParameters) =>
    TestBed.runInInjectionContext(() => authGuard(...guardParameters));

  beforeEach(() => {
    TestBed.configureTestingModule({});
  });

  it('should be created', () => {
    expect(executeGuard).toBeTruthy();
  });
});

/*
 * ===========================================================================
 *  NOTES: Unit testing in Angular
 * ===========================================================================
 *
 * WHAT IS A UNIT TEST?
 *   Code that checks ONE small piece (a guard, pipe, service, component) in
 *   isolation, automatically, in milliseconds, without opening the app.
 *   Files end with .spec.ts and sit next to the file they test.
 *
 * ---------------------------------------------------------------------------
 *  TEST RUNNERS: old way vs new way
 * ---------------------------------------------------------------------------
 *   Karma + Jasmine   OLD default (Angular 2 -> 20). Runs in a real browser. Slow.
 *                     Karma is deprecated.
 *   Jest              Popular alternative (via jest-preset-angular). Runs in Node.
 *                     NOT React-only: made by Facebook, but works with any JS project.
 *   Vitest            NEW default (Angular 21+). Used in THIS project. Very fast.
 *
 *   The test code looks almost the same in all three (describe / it / expect),
 *   so what you learn here works with Jest and Jasmine too.
 *
 *   End-to-end (E2E) tests (click through the real app in a browser) are different:
 *     Protractor (old, removed)  ->  Playwright or Cypress (now)
 *
 * ---------------------------------------------------------------------------
 *  RUNNING TESTS
 * ---------------------------------------------------------------------------
 *   npm test           watch mode: re-runs when you save a file
 *   npm run test:ci    run once (used in CI pipelines)
 *
 * ---------------------------------------------------------------------------
 *  THE BUILDING BLOCKS
 * ---------------------------------------------------------------------------
 *   describe('authGuard', () => { ... })   a GROUP of related tests
 *   it('should ...', () => { ... })         ONE test case; reads like a sentence
 *   expect(actual).toBe(expected)           an ASSERTION: the test fails if it's false
 *   beforeEach(() => { ... })               runs before EVERY `it` (fresh setup each time)
 *
 *   Common matchers:
 *     toBe(x)          exact same value (===)
 *     toEqual(obj)     same content (deep comparison for objects/arrays)
 *     toBeTruthy()     any "truthy" value
 *     toContain(x)     string/array contains x
 *     toHaveBeenCalled()  a spy/mock function was called
 *
 *   A good test follows ARRANGE -> ACT -> ASSERT:
 *     it('returns LG for Leanne Graham', () => {
 *       const pipe = new InitialsPipe();                 // arrange
 *       const result = pipe.transform('Leanne Graham');  // act
 *       expect(result).toBe('LG');                       // assert
 *     });
 *
 * ---------------------------------------------------------------------------
 *  ANGULAR-SPECIFIC: TestBed
 * ---------------------------------------------------------------------------
 *   TestBed creates a small Angular environment (an injector) just for the test.
 *     TestBed.configureTestingModule({ providers: [...] })   register fake/real services
 *     TestBed.inject(AuthService)                            get a service instance
 *     TestBed.createComponent(UserList)                      render a component
 *
 *   Pure classes (like InitialsPipe) don't need TestBed at all: just `new` them.
 *
 * ---------------------------------------------------------------------------
 *  WHAT THIS FILE DOES (generated by `ng generate guard`)
 * ---------------------------------------------------------------------------
 *   authGuard uses inject(), which only works inside an Angular "injection context".
 *   So the test wraps it:
 *     TestBed.runInInjectionContext(() => authGuard(...))
 *   executeGuard is that wrapper, so tests can call the guard like a normal function.
 *
 *   The single test only checks that the guard exists. A REAL test would check:
 *     - logged in      -> guard returns true
 *     - not logged in  -> guard returns a UrlTree to /login?returnUrl=...
 *   by providing a fake AuthService in configureTestingModule({ providers: [...] }).
 */
